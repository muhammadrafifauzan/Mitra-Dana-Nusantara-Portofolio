print("\n📈 RATA-RATA PERTUMBUHAN BULANAN:")
for yr in monthly["tahun"].unique():
    s = monthly[monthly["tahun"]==yr]
    print(f"  {yr}: DPK {s['dpk_growth'].mean():+.2f}%/bln")

# Fungsi forecast linear sederhana
def linear_forecast(series, n=6):
    x = np.arange(len(series))
    y = series.values
    slope = (len(x)*np.sum(x*y) - np.sum(x)*np.sum(y)) / (len(x)*np.sum(x**2) - np.sum(x)**2)
    intercept = (np.sum(y) - slope*np.sum(x)) / len(x)
    return slope * np.arange(len(series), len(series)+n) + intercept

# Forecast H2 2024
fc = linear_forecast(monthly["dpk"], n=6)
print("\n🔮 PROYEKSI DPK H2 2024 (Linear Trend):")
months_id = ["Jul","Ags","Sep","Okt","Nov","Des"]
base = monthly["dpk"].iloc[-1]
for mo, v in zip(months_id, fc):
    g = (v-base)/base*100
    print(f"  2024-{mo}: Rp {v/1e9:8.1f} M  ({'▲' if g>0 else '▼'} {abs(g):.1f}%)")

# Target skenario 2025
print("\n📋 SKENARIO TARGET 2025:")
for pct in [5,10,15]:
    t = base*(1+pct/100)
    print(f"  Target +{pct}%: Rp {t/1e9:.1f} M  | Tambahan: Rp {(t-base)/1e9:.1f} M")

print("\n✅ Forecast selesai!")

