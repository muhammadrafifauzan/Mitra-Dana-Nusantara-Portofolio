# Gunakan hasil cleaning dari dictionary cleaned_data
kpi = cleaned_data["kpi_cabang.csv"]

# Filter H1 2024
h1 = kpi[kpi["tahun"]==2024]
sc = h1.groupby(["kode_cabang","nama_cabang"]).agg(
    total_dpk=("dana_pihak_ketiga","sum"),
    avg_npl=("npl_pct","mean"),
    total_fee=("fee_based_income","sum"),
    total_nsb=("nasabah_baru","sum"),
    avg_pct=("pencapaian_pct","mean")
).reset_index()

# Fungsi scoring
def pct_score(s, asc=True):
    r = s.rank(pct=True)
    return (np.ceil((r if asc else 1-r)*5).clip(1,5)).astype(int)

# Hitung skor per indikator
sc["s_dpk"] = pct_score(sc["total_dpk"])
sc["s_npl"] = pct_score(sc["avg_npl"], asc=False)
sc["s_fee"] = pct_score(sc["total_fee"])
sc["s_nsb"] = pct_score(sc["total_nsb"])
sc["s_pct"] = pct_score(sc["avg_pct"])

# Skor akhir & predikat
sc["skor"]  = (sc["s_dpk"]*0.35 + sc["s_npl"]*0.25 + sc["s_fee"]*0.20 + sc["s_nsb"]*0.10 + sc["s_pct"]*0.10).round(2)
sc["predikat"] = pd.cut(sc["skor"], bins=[0,2,3,4,5], labels=["Poor","Fair","Good","Excellent"])
sc = sc.sort_values("skor", ascending=False).reset_index(drop=True)
sc.index += 1

# Output Scorecard
print("\n🏆 SCORECARD KINERJA CABANG:")
print(f"{'Rk':>3} {'Cabang':<30} {'DPK(Rp M)':>10} {'NPL%':>6} {'Skor':>6} {'Predikat'}")
