dorm  = rekening[rekening["status_rekening"].isin(["Dormant","Ditutup"])].groupby("id_nasabah").size().reset_index()
dorm.columns = ["id_nasabah","rek_bermasalah"]

# Gabungkan semua profil
df = nasabah.merge(last_trx, on="id_nasabah", how="left")
df = df.merge(freq_3m, on="id_nasabah", how="left")
df = df.merge(saldo, on="id_nasabah", how="left")
df = df.merge(dorm, on="id_nasabah", how="left")
df.fillna({"days_since":999,"freq_3m":0,"saldo":0,"rek_bermasalah":0}, inplace=True)

# Fungsi scoring churn
def churn_score(row):
    score = 0
    if row["days_since"] > 90:   score += 40
    elif row["days_since"] > 60: score += 20
    elif row["days_since"] > 30: score += 10
    if row["freq_3m"] == 0:      score += 30
    elif row["freq_3m"] < 3:     score += 15
    if row["saldo"] < 1e6:       score += 20
    elif row["saldo"] < 5e6:     score += 10
    if row["rek_bermasalah"] > 0: score += 10
    return min(score, 100)

df["churn_score"] = df.apply(churn_score, axis=1)
df["churn_risk"]  = pd.cut(df["churn_score"], bins=[-1,30,60,80,100],
    labels=["Low","Medium","High","Critical"])

