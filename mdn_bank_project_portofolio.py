"""
TAHAP 4 - CUSTOMER SEGMENTATION (RFM Analysis)
Bank MDN | Program Premier & Prioritas
Jalankan di Google Colab
"""
import pandas as pd
import numpy as np

print("=" * 60)
print("  CUSTOMER SEGMENTATION - BANK MDN")
print("=" * 60)

# Gunakan hasil cleaning dari dictionary cleaned_data
nasabah   = cleaned_data["nasabah.csv"]
rekening  = cleaned_data["rekening.csv"]
transaksi = cleaned_data["transaksi.csv"]

# ── Saldo per nasabah ─────────────────────────────────────────
saldo = rekening[rekening["status_rekening"]=="Aktif"].groupby("id_nasabah")["saldo"].sum().reset_index()
saldo.columns = ["id_nasabah","total_saldo"]

# ── RFM ──────────────────────────────────────────────────────
transaksi["tanggal"] = pd.to_datetime(transaksi["tanggal"], errors="coerce")
ref = pd.Timestamp("2024-07-01")
rfm = transaksi[transaksi["status"]=="Berhasil"].groupby("id_nasabah").agg(
    last_trx=("tanggal","max"),
    frekuensi=("id_transaksi","count"),
    monetary=("nominal","sum")
).reset_index()
rfm["recency"] = (ref - rfm["last_trx"]).dt.days

# ── Gabung ───────────────────────────────────────────────────
profil = nasabah.merge(saldo, on="id_nasabah", how="left")
profil = profil.merge(rfm[["id_nasabah","recency","frekuensi","monetary"]], on="id_nasabah", how="left")
profil.fillna({"total_saldo":0,"frekuensi":0,"monetary":0,"recency":365}, inplace=True)

# ── Scoring ──────────────────────────────────────────────────
profil["r"] = pd.cut(profil["recency"], bins=[0,30,60,90,180,9999], labels=[5,4,3,2,1]).astype(int)
profil["f"] = pd.cut(profil["frekuensi"], bins=[-1,4,9,14,19,9999], labels=[1,2,3,4,5]).astype(int)
profil["m"] = pd.cut(profil["total_saldo"], bins=[-1,1e6,10e6,50e6,100e6,9e12], labels=[1,2,3,4,5]).astype(int)
profil["rfm"] = profil["r"] + profil["f"] + profil["m"]
profil["segment"] = pd.cut(profil["rfm"], bins=[0,5,8,11,15],
    labels=["At Risk","Potential","Loyal","Champions"])

# ── Output ───────────────────────────────────────────────────
print("\n📊 HASIL SEGMENTASI RFM:")
print(profil.groupby("segment").agg(
    jumlah=("id_nasabah","count"),
    avg_saldo=("total_saldo","mean"),
    avg_frekuensi=("frekuensi","mean"),
    total_saldo=("total_saldo","sum")
).round(0).to_string())

print("\n📋 STRATEGI PER SEGMEN:")
strategies = {
    "Champions":  "MDN Premier Card + Private Banking invitation",
    "Loyal":      "Upgrade Prioritas + cross-sell deposito/reksa dana",
    "Potential":  "Edukasi produk investasi + promo referral",
    "At Risk":    "Hubungi RM, tawaran retensi, survey alasan churn"
}
for seg, act in strategies.items():
    n = len(profil[profil["segment"]==seg])
    print(f"  {seg:12s} ({n:3d} nasabah): {act}")

# Simpan hasil ke file CSV (opsional di Colab)
profil[["id_nasabah","nama_lengkap","segmen_nasabah","total_saldo","frekuensi","rfm","segment","no_telepon"]].to_csv(
    "/content/output_segmentasi_rfm.csv", index=False
)
print("\n✅ Hasil disimpan ke output_segmentasi_rfm.csv")

